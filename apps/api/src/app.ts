import Fastify, { LogController } from 'fastify';
import { HealthResponseSchema } from '@crypto/contracts';
import type { FixtureReport, HealthResponse } from '@crypto/contracts';
import { RuntimeConfigSchema } from '@crypto/core';
import type { RuntimeConfig } from '@crypto/core';
export { buildMarketQueryApp } from './market-data.js';
export { buildNewsReviewApp } from './news-review.js';
export { buildEventStudyApp, buildEventControlsApp } from './event-study.js';

export function buildApp(config: RuntimeConfig, fixtures: FixtureReport) {
  const settings = RuntimeConfigSchema.parse(config);
  // Validate and copy startup state; health never claims unverified fixture readiness.
  const snapshot = HealthResponseSchema.parse({
    schemaVersion: 'health.v1',
    status: 'ok',
    service: 'crypto-research-api',
    mode: settings.dataMode,
    execution: 'disabled',
    checkedAt: new Date().toISOString(),
    fixtures,
    dependencies: { postgres: 'not-required', redis: 'not-required' },
  });
  const app = Fastify({
    logger: {
      level: settings.logLevel,
      redact: ['req.headers.authorization', 'req.headers.cookie', 'res.headers.set-cookie'],
    },
    // Correlation IDs are generated by Fastify; arbitrary incoming IDs are not trusted.
    requestIdHeader: false,
    bodyLimit: 16384,
    logController: new LogController({ disableRequestLogging: true }),
  });

  app.get('/health', (request, reply): HealthResponse => {
    reply.header('x-request-id', request.id).header('cache-control', 'no-store');
    return HealthResponseSchema.parse({ ...snapshot, checkedAt: new Date().toISOString() });
  });

  return app;
}
