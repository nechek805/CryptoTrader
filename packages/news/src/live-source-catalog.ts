export function initialLiveNewsSources(now = Date.now()): LiveNewsSource[] {
  return [
    ...entries.map(
      ([
        id,
        name,
        homepage,
        category,
        notes,
        feed,
        approved = false,
        ai = false,
        excerpt = 0,
        reference,
        settings,
      ]) =>
        LiveNewsSourceSchema.parse({
          id,
          name,
          homepage,
          category,
          notes,
          adapter: feed ? 'RSS_ATOM' : 'SETUP_REQUIRED',
          feedUrl: feed ?? null,
          articleOrigins: [new URL(feed ?? homepage).origin],
          enabled: approved,
          pollIntervalSeconds: 300,
          independenceGroup: id.startsWith('bls-') ? 'us-bls' : id,
          language: 'en',
          collectionApproved: approved,
          aiAllowed: ai,
          maxExcerptChars: excerpt,
          permissionReference: reference ?? homepage,
          revision: 1,
          createdAt: now,
          updatedAt: now,
          ...settings,
        }),
    ),
    ...freeNewsSources(now),
  ];
}
